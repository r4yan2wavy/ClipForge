"""Create a test-pattern/tone fixture. No speech recognition or AI is performed.

Fixture captions are deliberately supplied text, not a transcript of the tone.
Keep the resulting artifact private; this is a mechanics test, not a publishable clip.
"""
import argparse
from pathlib import Path

from clipforge.common import (Candidate, CandidateList, Metadata, SourceManifest, Span,
                             Transcript, Word, atomic_json, load_settings, run_command)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", default="config.json")
    args = parser.parse_args()
    cfg = load_settings(args.config)
    folder = cfg.resolve("inbox")
    folder.mkdir(parents=True, exist_ok=True)
    video, music = folder / "demo-source.mp4", cfg.resolve("examples/demo-tone.wav")
    music.parent.mkdir(parents=True, exist_ok=True)
    run_command([cfg.render.ffmpeg, "-nostdin", "-v", "error", "-y", "-f", "lavfi", "-i",
                 "testsrc2=size=320x180:rate=5:duration=22", "-f", "lavfi", "-i",
                 "sine=frequency=440:sample_rate=48000:duration=22", "-shortest", "-c:v", "libx264",
                 "-preset", "ultrafast", "-pix_fmt", "yuv420p", "-c:a", "aac", str(video)])
    run_command([cfg.render.ffmpeg, "-nostdin", "-v", "error", "-y", "-f", "lavfi", "-i",
                 "sine=frequency=880:sample_rate=48000:duration=0.5", str(music)])
    words = [Word(start_s=0.4 + i, end_s=0.9 + i, text=f"Fixture {i}.") for i in range(20)]
    transcript = Transcript(language="en", duration_s=22.0, words=words,
                            spans=[Span(id="s000000", start_s=0.4, end_s=10.4, text="Synthetic test pattern."),
                                   Span(id="s000001", start_s=10.4, end_s=20.4, text="Fixture captions are not speech.")])
    fixtures = cfg.resolve("examples/fixtures")
    atomic_json(fixtures / "transcript.json", transcript.model_dump())
    selection = CandidateList(clips=[Candidate(start_id="s000000", end_id="s000001", start_s=0.4,
                                end_s=20.4, hook_id="s000000", payoff_id="s000001", score=0.8,
                                reason="Synthetic mechanics fixture only.", needs_visual_review=True)])
    atomic_json(fixtures / "candidates.json", selection.model_dump())
    atomic_json(fixtures / "metadata.json", Metadata(title="Synthetic rendering test",
        description="Test pattern and tones with fixture captions. No AI inference or real spoken transcript.",
        tags=["synthetic test"]).model_dump())
    manifest = SourceManifest(media_path=str(video), rights_category="original",
        permission_reference="Generated locally by FFmpeg testsrc2 and sine; synthetic testing only.",
        creator_credit="Synthetic FFmpeg fixture generated by the operator.",
        contribution="Mechanics verification only, not an editorial contribution for publication.",
        transcript_path=str(fixtures / "transcript.json"), candidates_path=str(fixtures / "candidates.json"),
        metadata_path=str(fixtures / "metadata.json"), music_path=str(music),
        music_license_reference="Locally generated sine test signal.",
        music_attribution="Test tone generated locally.")
    # Only source manifests go in inbox/*.json; fixtures live elsewhere.
    atomic_json(folder / "demo.json", manifest.model_dump())
    print(f"Generated synthetic test manifest: {folder / 'demo.json'}")


if __name__ == "__main__":
    main()
